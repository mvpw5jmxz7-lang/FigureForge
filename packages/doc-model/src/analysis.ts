/**
 * Statistical analyses attached to a figure.
 *
 * The document stores the *request* and the *cached result* side by side, plus
 * a hash of the inputs that produced the result. Reopening a project rehashes
 * the inputs and flags any analysis whose data or options have drifted, so a
 * figure can never silently display a p-value that its data no longer supports.
 *
 * Computation itself happens in the Python service; nothing here runs a test.
 */

import type { Series } from './data.js';
import type { AnalysisId, DatasetId, NodeId } from './nodes.js';

export type StatTest =
  | 'ttest-independent'
  | 'ttest-paired'
  | 'ttest-welch'
  | 'mann-whitney'
  | 'wilcoxon'
  | 'anova-one-way'
  | 'anova-rm'
  | 'kruskal-wallis'
  | 'chi-square'
  | 'pearson'
  | 'spearman'
  | 'linear-regression';

export type Alternative = 'two-sided' | 'less' | 'greater';

/** Multiple-comparison correction applied across a family of tests. */
export type Correction = 'none' | 'bonferroni' | 'holm' | 'benjamini-hochberg' | 'tukey' | 'dunn';

export interface AnalysisOptions {
  alternative: Alternative;
  correction: Correction;
  alpha: number;
  /** Assume unequal variances (Welch). Ignored by tests where it is meaningless. */
  welch: boolean;
}

export const defaultAnalysisOptions = (): AnalysisOptions => ({
  alternative: 'two-sided',
  correction: 'none',
  alpha: 0.05,
  welch: true,
});

/** Which series of a dataset the test consumes. */
export interface AnalysisSpec {
  datasetId: DatasetId;
  /** Series names, resolved through `toSeries`. */
  groups: readonly string[];
}

export interface Comparison {
  /** Series names being compared. */
  groupA: string;
  groupB: string;
  statistic: number;
  p: number;
  /** After multiple-comparison correction; equals `p` when correction is 'none'. */
  pAdjusted: number;
  df: number | null;
  ci: readonly [number, number] | null;
  effectSize: number | null;
  effectSizeName: string | null;
  n: readonly number[];
}

export interface StatResult {
  test: StatTest;
  /** Omnibus statistic, for ANOVA/Kruskal-Wallis. Null for pairwise-only tests. */
  omnibus: { statistic: number; p: number; df: readonly number[] | null } | null;
  comparisons: readonly Comparison[];
  /** Ready-to-paste manuscript methods sentence, generated by the service. */
  methodsSentence: string;
  /** Assumption checks worth surfacing, e.g. a failed normality test. */
  warnings: readonly string[];
  softwareVersions: Readonly<Record<string, string>>;
}

export interface Analysis {
  id: AnalysisId;
  name: string;
  test: StatTest;
  spec: AnalysisSpec;
  options: AnalysisOptions;
  /**
   * The plot this analysis annotates, when it was run from one. A plot carries
   * at most one analysis: re-running a test on the same panel replaces the
   * previous result rather than accumulating alongside it.
   *
   * Optional so documents predating the field still load unmigrated.
   */
  plotId?: NodeId | null;
  /** Hash of (spec + options + the actual input values) at compute time. */
  inputHash: string;
  result: StatResult | null;
  computedAt: string | null;
}

// ---------------------------------------------------------------------------
// Significance annotation
// ---------------------------------------------------------------------------

/**
 * Convention used across Nature/Cell figure legends. Note this reads the
 * *adjusted* p-value: annotating uncorrected p-values on a multi-comparison
 * figure is exactly the error the quality checker exists to catch.
 */
export function significanceStars(pAdjusted: number): string {
  if (!Number.isFinite(pAdjusted)) return 'ns';
  if (pAdjusted <= 0.0001) return '****';
  if (pAdjusted <= 0.001) return '***';
  if (pAdjusted <= 0.01) return '**';
  if (pAdjusted <= 0.05) return '*';
  return 'ns';
}

/** Journal-style p-value text, e.g. "P = 0.032" or "P < 0.001". */
export function formatP(p: number, prefix = 'P'): string {
  if (!Number.isFinite(p)) return `${prefix} = n/a`;
  if (p < 0.001) return `${prefix} < 0.001`;
  if (p < 0.01) return `${prefix} = ${p.toFixed(3)}`;
  return `${prefix} = ${p.toFixed(2)}`;
}

// ---------------------------------------------------------------------------
// Input hashing (staleness detection)
// ---------------------------------------------------------------------------

/** JSON with object keys sorted, so hashing is insensitive to key order. */
export function stableStringify(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value) ?? 'null';
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableStringify(v)}`).join(',')}}`;
}

/**
 * FNV-1a over the canonical form, widened to 64 bits by running two offset
 * bases. Not cryptographic — this only needs to detect accidental drift.
 */
export function hashInputs(...parts: unknown[]): string {
  // Separated by U+0000, written as an escape: JSON output can never contain a
  // literal NUL, so no two different groupings of parts can collide on the
  // same joined string.
  const text = parts.map(stableStringify).join('\u0000');
  let h1 = 0x811c9dc5;
  let h2 = 0x01000193;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 0x01000193) >>> 0;
    h2 = Math.imul(h2 ^ c, 0x811c9dc5) >>> 0;
  }
  return h1.toString(16).padStart(8, '0') + h2.toString(16).padStart(8, '0');
}

export const isStale = (analysis: Analysis, currentHash: string): boolean =>
  analysis.result !== null && analysis.inputHash !== currentHash;

/**
 * The hash an analysis should carry, given the values it was run over.
 *
 * One definition, used when storing a result and when checking whether it has
 * drifted. Composing the hash separately at each call site is how a stored hash
 * and a recomputed one come to disagree over nothing, which reads as "the data
 * changed" on a figure nobody has touched.
 */
export function analysisInputHash(
  options: { test: StatTest; correction: Correction },
  values: readonly (readonly number[])[],
  x?: readonly number[],
): string {
  // The 2-argument form must keep hashing exactly as before: every already-
  // saved project's inputHash was computed that way, and passing a 3rd
  // argument only when x is undefined would flip every existing analysis to
  // "stale" the moment a project is reopened.
  return x === undefined
    ? hashInputs({ test: options.test, correction: options.correction }, values)
    : hashInputs({ test: options.test, correction: options.correction }, values, x);
}

/**
 * The x-values to fold into an analysis's hash, if any.
 *
 * A persisted analysis can only have exactly one group in `spec.groups` when
 * it is a series correlated against its own x — every other test requires at
 * least two groups. So "exactly one series" is a safe, sufficient signal; no
 * per-test check is needed here.
 */
export function xForHash(series: readonly Series[]): readonly number[] | undefined {
  return series.length === 1 ? series[0]?.x : undefined;
}
