/**
 * Put the sample's micrograph bytes into an asset store.
 *
 * Must run everywhere `createSampleDocument()` does — the launch initialiser
 * *and* `newFigure`, which clears the store first. Miss the second and New
 * Figure opens with three image nodes pointing at nothing.
 *
 * JPEG is directly displayable, so `original` and `display` are the same
 * bytes, exactly as `assets.ts` describes for any format a browser can decode.
 */
export function seedSampleAssets(store: {
  add: (id: string, bytes: {
    original: Uint8Array;
    mimeType: string;
    display: Uint8Array;
    displayMimeType: string;
  }) => void;
}): void {
  for (const sample of SAMPLE_MICROGRAPHS) {
    const binary = atob(sample.base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
    store.add(sample.id, {
      original: bytes,
      mimeType: sample.mimeType,
      display: bytes,
      displayMimeType: sample.mimeType,
    });
  }
}
