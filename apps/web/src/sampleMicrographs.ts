/**
 * The micrographs the sample figure opens with.
 *
 * Bytes, not document metadata — which is why they live here rather than in
 * `sample.ts`. Asset bytes are held in `AssetStore` outside the document (see
 * `assets.ts`: putting a micrograph in the document would clone it into the
 * undo history on every unrelated edit), and `createSampleDocument()` is also
 * called from Node by `scripts/archive-memory.ts`, so it must stay free of
 * anything a browser supplies. It declares the `Asset` records; this module
 * supplies what they point at, and `App.tsx` seeds the store.
 *
 * Re-encoded from the PNG/JPEG originals in `reference-and-test-files/` at
 * JPEG quality 70. The originals are 323 KB and 565 KB, which base64 to 430 KB
 * and 750 KB of source; these are 14–21 KB each.
 *
 * Kept at their native 800 x 600 rather than downscaled. At the ~30 mm a tile
 * takes in the sample's three-across montage that is well past 300 dpi, so the
 * figure opens with no `checkImageResolution` finding — a downscale to 640 px
 * would land at 295 dpi and greet every new user with a warning.
 */

